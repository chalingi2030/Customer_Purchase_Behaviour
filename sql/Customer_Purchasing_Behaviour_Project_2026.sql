-- Question 15: payment method and freguency of puechases by segment

SELECT payment_method,
       frequency_of_purchases,
       COUNT(*) AS customers,
       SUM(COUNT(*)) OVER (PARTITION BY payment_method) AS payment_method_total
FROM customers
GROUP BY payment_method, frequency_of_purchases
ORDER BY payment_method_total DESC, customers DESC;

-- PayPal is the most used payment method overall, with 673 customers
-- across all purchase frequencies (17.4% of all customers).
-- The largest single group is Credit Card customers who buy every 3 months,
-- with 112 customers (2.9% of all customers).
-- Customers are spread thinly across payment methods and frequencies,
-- so no single combination dominates



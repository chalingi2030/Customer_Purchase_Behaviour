-- Question 10: Customer Loyalty Segmentation
-- To classify customers as: 
-- New by 1 purchase,
-- Returning by 2-10 purchase,
-- Loyal customer with more than 10 purchase

WITH customer_type AS (
SELECT customer_id, previous_purchases,
CASE
	WHEN previous_purchases = 1 THEN 'New'
    WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning'
    WHEN previous_purchases > 10 THEN 'Loyal'
  END AS customer_segment
FROM customers
)
SELECT customer_segment, COUNT(*) AS Number_of_customers
FROM customer_type
GROUP BY customer_segment;

-- Loyal customers with more than 10 purchase leads with a total number of 3,085
-- returning customers who purchase 2-10 items are 695 in total
-- While new customers with just 1 purchase are 83 in number


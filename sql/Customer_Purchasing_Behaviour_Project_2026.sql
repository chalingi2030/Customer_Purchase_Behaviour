-- Question 1: Total Revenue by gender
-- To compare the total revenue generated by female vs male customers

SELECT gender, SUM(purchase_amount) AS revenue
FROM customers
GROUP BY gender;

-- Male customers leads by total revenue of USD 155,438
-- While female customers return a less total revenue of USD 75,191

-- Question 2: Type of customers using Discounts
-- To identify customers who received a discount but still spent
-- At or above the overall average purchase amount

SELECT COUNT(*) FROM customers WHERE discount_applied = 'YES';

-- 1640 customers received a discount (42.5% of all customers)

SELECT COUNT(*) AS discounted_above_avg
FROM customers
WHERE discount_applied = 'YES'
  AND purchase_amount >= (SELECT AVG(purchase_amount) FROM customers);

-- 816 of the 1,640 discounted customers (49.8%) still spent at or above
-- the average purchase amount of USD 59.70. This is 21.1% of all customers.
-- These customers did not need a discount to spend above average, so they
-- are the group where discount budget may be going to waste.


-- Question 3: Average Purchase Amount by shipping_type
-- To compare how shipping choice affects average customers spending

SELECT shipping_type, ROUND(AVG(purchase_amount), 2) AS "Avg_purchase_Amount_by_shipping_type"
FROM customers
GROUP BY shipping_type
ORDER BY Avg_purchase_Amount_by_shipping_type DESC;

-- The 2-Day shipping type leads by an Average amount of 60.59
-- Free Shipping type becomes the second with an average of 60.37
-- Express shipping type takes the third position with an average of 60.34
-- Store Pickup shipping takes the forth position with an average of 59.91
-- Next Day Air shipping takes the fifth position with an average of 58.62
-- while Standard shipping type is the last and returns average of 58.41

-- Question 4: Top 5 High rated products
-- To identify the five products with the best average customer reviews

SELECT item_purchased AS products, ROUND(AVG(review_rating), 2) AS avg_product_rating
FROM customers
GROUP BY item_purchased
ORDER BY AVG(review_rating) DESC
LIMIT 5;

-- Gloves takes the first position by an average of 3.86
-- sandals takes the second position by an average of 3.84
-- while boots 3.82, Hat 3.8 and Skirt by 3.79

-- Question 5: Products that are mostly driven by discounts
-- To identify the products with highest percentage of purchases made using discounts

SELECT 
item_purchased, ROUND(SUM(CASE WHEN discount_applied = 'YES' THEN 1 ELSE 0 END)
/
COUNT(*) * 100, 2) AS discount_rate
FROM customers
GROUP BY item_purchased
ORDER BY discount_rate DESC
LIMIT 5;

-- Hat and Sneakers Returns the highest Discount rate of 49.67%, 49.66% 
-- Coat takes the third position with 48.43%
-- While Sweater 47.20% and Pants 46.43%

-- Question 6: Subscription impact on spending
-- To compare average spending and total revenue between subscribed and non-subscribed customers

SELECT 
subscription_status, COUNT(*) AS total_customers,
ROUND(AVG(purchase_amount), 2) AS Avg_spent,
SUM(purchase_amount) AS total_amount
FROM customers
GROUP BY subscription_status
ORDER BY SUM(purchase_amount) DESC;

-- The non-subscribed customers leads by a total number of 2830 
-- And spent an average of USD 59.81
-- Returns a total revenue of USD 169,252
-- While the subscribed customers are 1,033 in total with an average spent of USD 59.42
-- And returns a total revenue of USD 61,377

-- Question 7: Repeat Buyers VS Subscription status
-- To compare the repeat buyers rate between subscribed and non-subscribed customers

SELECT subscription_status,
       COUNT(*) AS customers,
       SUM(previous_purchases > 5) AS repeat_buyers,
       ROUND(SUM(previous_purchases > 5) / COUNT(*) * 100, 1) AS repeat_rate_pct
FROM customers
GROUP BY subscription_status;

-- 88.4% of non-subscribed customers (2,503 of 2,830) are repeat buyers,
-- compared with 90.9% of subscribed customers (939 of 1,033).
-- Subscribers are slightly more likely to be repeat buyers.
-- Non-subscribers have more repeat buyers in total only because there
-- are almost three times as many of them.


-- Question 8: Revenue contribution buy age group
-- To identify which age group contributes the most revenue

WITH banded AS (
  SELECT purchase_amount,
         CASE WHEN age BETWEEN 18 AND 25 THEN '18-25'
              WHEN age BETWEEN 26 AND 35 THEN '26-35'
              WHEN age BETWEEN 36 AND 45 THEN '36-45'
              WHEN age BETWEEN 46 AND 55 THEN '46-55'
              WHEN age BETWEEN 56 AND 65 THEN '56-65'
              WHEN age >= 66 THEN '66+'
              ELSE 'Other' END AS age_band
  FROM customers
)
SELECT age_band, COUNT(*) AS customers,
       SUM(purchase_amount) AS total_revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM banded
GROUP BY age_band
ORDER BY total_revenue DESC;
 
 -- Age_band between 46-55 returns the highest total revenue of USD 44,927 and average spend of 60.47
 -- Age_band between 26-35 returns the second highest revenue of USD 44,008 and average spend of 59.79
 -- Age band between 56-65 returns the third total revenue of USD 43,930 and average spend of 58.97
 -- Age band between 36-45 takes the forth postion with total revenue of USD 42,853 and average spend of 59.35
 -- Age band between 18-25 takes the fift position  with total revenue of USD 34,281 and average spend of 60.57
 -- While 66+ of age returns the lowest total revenue of USD 20,630 and average spend of 58.77
 
 
-- Question 9: Finding the most purchased products in each category
-- To identify the best selling products within each category

WITH item_counts AS (
SELECT category, item_purchased, COUNT(customer_id) AS total_orders,
RANK() OVER(PARTITION BY category ORDER BY COUNT(customer_id) DESC
) AS item_rank

FROM customers
GROUP BY category, item_purchased

)
SELECT 
item_rank,
category,
item_purchased,
 total_orders
FROM item_counts
WHERE item_rank <= 3;

